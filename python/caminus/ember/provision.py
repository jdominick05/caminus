"""The one privileged step of `caminus ember setup`: a root shell script, safe to rerun, that checks itself.

It creates the agent's Unix account, the bridge group and folders (req, res, notes, leases), SSH login for the owner's
key only, and lingering for the agent's user services. Every step looks first and changes only what is missing or wrong,
so a second run changes nothing and a partial setup is finished, not duplicated. It ends by checking every item and
exits non-zero when one is wrong. DRY_RUN=1 prints the changes instead of making them (and skips the root check).

Standard library only; the owner runs it with sudo (the agent never does).
"""
import shlex

# Modes: the bridge folder is sticky (1770): only a file's owner or root may delete it, so an agent in the group cannot
# remove the owner's STOP file. Its subfolders are setgid (2770): files made there keep the bridge group, never
# readable to others.
BRIDGE_MODE, SUB_MODE = '1770', '2770'
SUBDIRS = ('req', 'res', 'notes', 'leases')

TEMPLATE = r'''#!/bin/sh
# caminus ember: the privileged setup (generated by `caminus ember setup`). Safe to rerun; it checks itself at the end.
#   sudo sh {path}
set -eu
AGENT={user}
GROUP={group}
OWNER={owner}
BRIDGE={bridge}
PUBKEY={pubkey}

DRY=${{DRY_RUN:-}}
run() {{ if [ -n "$DRY" ]; then echo "would run: $*"; else "$@"; fi; }}
say() {{ echo "setup: $*"; }}
if [ -z "$DRY" ] && [ "$(id -u)" -ne 0 ]; then echo "run it with sudo: sudo sh $0" >&2; exit 2; fi

# 1. SSH: the owner reaches the agent account over localhost with one key.
if ! command -v sshd >/dev/null 2>&1 && [ ! -x /usr/sbin/sshd ]; then
  say "installing openssh-server"
  run apt-get install -y openssh-server || {{ run apt-get update && run apt-get install -y openssh-server; }}
fi
if command -v systemctl >/dev/null 2>&1 && ! systemctl is-active --quiet ssh 2>/dev/null; then
  say "starting ssh"; run systemctl enable --now ssh
fi

# 2. The agent account: a normal user with no password (login by key only).
if ! id "$AGENT" >/dev/null 2>&1; then
  say "creating user $AGENT"; run useradd -m -s /bin/bash "$AGENT"
fi
if [ -z "$DRY" ] || id "$AGENT" >/dev/null 2>&1; then
  case "$(passwd -S "$AGENT" 2>/dev/null | awk '{{print $2}}')" in L|LK) ;; *) run passwd -l "$AGENT" >/dev/null ;; esac
fi

# 3. The bridge group: the agent and the owner share it; GPU groups for the agent's own GPU work.
getent group "$GROUP" >/dev/null 2>&1 || {{ say "creating group $GROUP"; run groupadd "$GROUP"; }}
for g in "$GROUP" render video; do
  getent group "$g" >/dev/null 2>&1 || continue
  id -nG "$AGENT" 2>/dev/null | tr ' ' '\n' | grep -qx "$g" || {{ say "adding $AGENT to $g"; run usermod -aG "$g" "$AGENT"; }}
done
if ! id -nG "$OWNER" | tr ' ' '\n' | grep -qx "$GROUP"; then
  say "adding $OWNER to $GROUP (log out and back in, or run: newgrp $GROUP)"; run usermod -aG "$GROUP" "$OWNER"
fi

# 4. The bridge folders: root-owned, the group reads and writes; sticky top, setgid below.
fix_dir() {{  # path mode
  [ -d "$1" ] || run mkdir -p "$1"
  [ "$(stat -c '%U:%G' "$1" 2>/dev/null)" = "root:$GROUP" ] || run chown "root:$GROUP" "$1"
  [ "$(stat -c '%a' "$1" 2>/dev/null)" = "$2" ] || run chmod "$2" "$1"
}}
fix_dir "$BRIDGE" {bridge_mode}
for d in {subdirs}; do fix_dir "$BRIDGE/$d" {sub_mode}; done

# 5. The agent's user services (its resident, its jobs) keep running after it logs out.
if command -v loginctl >/dev/null 2>&1; then
  [ "$(loginctl show-user "$AGENT" -p Linger --value 2>/dev/null)" = yes ] || {{ say "enabling linger for $AGENT"; run loginctl enable-linger "$AGENT"; }}
fi

# 6. SSH login: the owner's key only, from localhost, no forwarding.
HOMEDIR=$(getent passwd "$AGENT" | cut -d: -f6); HOMEDIR=${{HOMEDIR:-/home/$AGENT}}
LINE="from=\"127.0.0.1,::1\",no-agent-forwarding,no-X11-forwarding,no-port-forwarding $PUBKEY"
AUTH="$HOMEDIR/.ssh/authorized_keys"
if [ -n "$DRY" ] && [ -d "$HOMEDIR" ] && [ ! -x "$HOMEDIR" ]; then
  echo "cannot check the key in $AUTH without root (a real run does)"
else
[ -d "$HOMEDIR/.ssh" ] || run install -d -m 700 -o "$AGENT" -g "$AGENT" "$HOMEDIR/.ssh"
if ! grep -qxF "$LINE" "$AUTH" 2>/dev/null; then
  say "authorizing the owner's key"
  if [ -n "$DRY" ]; then echo "would append the key line to $AUTH"; else printf '%s\n' "$LINE" >> "$AUTH"; fi
fi
if [ -z "$DRY" ]; then chown "$AGENT:$AGENT" "$AUTH"; chmod 600 "$AUTH"; chmod 700 "$HOMEDIR/.ssh"; fi
fi

# 7. The check: every item, PASS or FAIL.
[ -n "$DRY" ] && {{ echo "dry run: nothing changed"; exit 0; }}
fail=0
check() {{ if eval "$2"; then echo "PASS $1"; else echo "FAIL $1"; fail=1; fi; }}
check "user $AGENT" 'id "$AGENT" >/dev/null 2>&1'
check "group $GROUP (agent and owner)" 'id -nG "$AGENT" | grep -qw "$GROUP" && id -nG "$OWNER" | grep -qw "$GROUP"'
check "bridge $BRIDGE root:$GROUP {bridge_mode}" '[ "$(stat -c "%U:%G %a" "$BRIDGE")" = "root:$GROUP {bridge_mode}" ]'
for d in {subdirs}; do
  check "bridge/$d root:$GROUP {sub_mode}" '[ "$(stat -c "%U:%G %a" "$BRIDGE/'"$d"'")" = "root:$GROUP {sub_mode}" ]'
done
check "owner key authorized" 'grep -qxF "$LINE" "$AUTH"'
check "ssh running" 'systemctl is-active --quiet ssh 2>/dev/null || pgrep -x sshd >/dev/null'
if [ "$fail" -ne 0 ]; then echo "setup: some checks failed (above)"; exit 1; fi
echo "setup: done. Next, as yourself: caminus ember setup"
'''


def script(user, group, owner, bridge, pubkey, path):
    """The root script for these names. Every value is shell-quoted; the public key must be one line."""
    if '\n' in pubkey.strip() or not pubkey.strip():
        raise ValueError('the public key must be one non-empty line')
    q = shlex.quote
    return TEMPLATE.format(user=q(user), group=q(group), owner=q(owner), bridge=q(bridge.rstrip('/')),
                           pubkey=q(pubkey.strip()), path=path, bridge_mode=BRIDGE_MODE, sub_mode=SUB_MODE,
                           subdirs=' '.join(SUBDIRS))
