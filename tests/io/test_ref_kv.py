"""Fixed Q8 KV wire vectors and refusals; CPU only, no model files.

python -I tests/io/test_ref_kv.py
"""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'python'))

import numpy as np
from caminus.ref_kv import Q8KVLayout, encode_q8_kv, decode_q8_kv
from caminus import own_dequant

ok = True


def check(condition, message):
    global ok
    ok &= bool(condition)
    print('PASS' if condition else 'FAIL', message, flush=True)


def refuses(fn, message):
    try:
        fn()
    except ValueError:
        check(True, message)
    else:
        check(False, message)


def block(scale_bytes, codes):
    return bytes(scale_bytes) + np.array(codes + [0] * (32 - len(codes)), np.int8).tobytes()


def f32_bits(word):
    return np.array([word], np.uint32).view(np.float32)[0]


layout = Q8KVLayout(1, 128)
base = np.zeros(32, np.float32)
base[:11] = [127, .5, -.5, 1.5, -1.5, 2.5, -2.5,
             np.nextafter(np.float32(.5), np.float32(0)),
             -np.nextafter(np.float32(.5), np.float32(0)),
             np.nextafter(np.float32(.5), np.float32(1)),
             -np.nextafter(np.float32(.5), np.float32(1))]
k = np.tile(base, 4).reshape(1, 1, 128)
v = k * np.float32(2)
codes = [127, 1, -1, 2, -2, 3, -3, 0, 0, 1, -1]
want = block([0, 0x3c], codes) * 4 + block([0, 0x40], codes) * 4
packed = encode_q8_kv(k, v, layout)
check(packed.tobytes() == want, 'K then V, signs and roundf ties away, adjacent values below/above ties')
dk, dv = decode_q8_kv(packed, layout)
check(dk[0, 0, :11].tolist() == codes and dv[0, 0, :11].tolist() == [2 * x for x in codes],
      'fixed scale-one/two blocks decode to independent known values')

# These bit patterns are fixed regression inputs, not generated by the codec.
# Half d rounds to 1, while the fp32 scale gives code 63 (half-scale division gives 64).
base[:] = 0
base[:3] = [f32_bits(0x42fe1382), f32_bits(0x427e0a3d), -f32_bits(0x427e0a3d)]
k = np.tile(base, 4).reshape(1, 1, 128)
want = block([0, 0x3c], [127, 63, -63]) * 8
check(encode_q8_kv(k, k, layout).tobytes() == want,
      'stored half scale rounds independently of fp32 scale used by codes')
for scale_word, half_word in ((0x3f801000, 0x3c00), (0x3f803000, 0x3c02)):
    base[:] = 0
    base[0] = f32_bits(scale_word) * np.float32(127)
    k = np.tile(base, 4).reshape(1, 1, 128)
    want = block([half_word & 255, half_word >> 8], [127]) * 8
    check(encode_q8_kv(k, k, layout).tobytes() == want,
          'stored half scale ties round to even at both adjacent endpoints')

# x / d is exactly .5, but x * fp32(1 / d) is the float immediately below .5.
base[:] = 0
base[:3] = [3, f32_bits(0x3c418306), -f32_bits(0x3c418306)]
k = np.tile(base, 4).reshape(1, 1, 128)
want = block([0x0c, 0x26], [127, 0, 0]) * 8
check(encode_q8_kv(k, k, layout).tobytes() == want,
      'fp32 reciprocal then product is preserved at a rounding boundary')

base[:] = 0
base[:3] = [np.float32(1.27e-6), -np.float32(1.27e-6), 0]
k = np.tile(base, 4).reshape(1, 1, 128)
raw = encode_q8_kv(k, k, layout)
check(raw.tobytes() == block([0, 0], [127, -127, 0]) * 8,
      'normal fp32 scale may round to stored half zero while codes survive')
a, b = decode_q8_kv(raw, layout)
check(not a.any() and not b.any(), 'stored half underflow loses decoded values without changing codes')
base[:3] = [np.float32(127 * 2**-24), -np.float32(127 * 2**-24), 0]
k = np.tile(base, 4).reshape(1, 1, 128)
raw = encode_q8_kv(k, k, layout)
a, b = decode_q8_kv(raw, layout)
check(raw.tobytes() == block([1, 0], [127, -127, 0]) * 8
      and np.array_equal(a, k) and np.array_equal(b, k),
      'smallest half subnormal scale has explicit bytes and exact decoded values')

for heads, dim, row_bytes in ((1, 128, 272), (1, 256, 544), (3, 128, 816), (3, 256, 1632)):
    shape = (3, heads, dim)
    ly = Q8KVLayout(heads, dim)
    zero = np.zeros(shape, np.float32)
    raw = encode_q8_kv(zero, -zero, ly)
    check(ly.row_bytes == row_bytes and ly.cache_bytes(7) == 7 * row_bytes
          and raw.shape == (3, row_bytes) and raw.nbytes == 3 * row_bytes and not raw.any(),
          f'{heads} heads, width {dim}: physical byte counts and canonical signed zeros')
    # Distinct head, K/V and row scales ensure the flattened order is observable.
    signed = np.tile(np.array([-127, 127, -1, 1] + [0] * 28, np.float32), dim // 32)
    factors = np.arange(1, 3 * heads + 1, dtype=np.float32).reshape(3, heads, 1)
    x = signed * factors
    y = x * np.float32(2)
    raw = encode_q8_kv(x, y, ly)
    expected_blocks = b''
    for row in range(3):
        for multiplier in (1, 2):
            for head in range(heads):
                scale = (row * heads + head + 1) * multiplier
                # These small integer scales are exactly representable in half.
                expected_blocks += block(np.array([scale], '<f2').view(np.uint8).tolist(),
                                         [-127, 127, -1, 1]) * (dim // 32)
    check(raw.tobytes() == expected_blocks, f'{heads} heads, width {dim}: independent K/V/head/row order')
    a, b = decode_q8_kv(raw, ly)
    oracle = own_dequant.dequant(raw.reshape(-1), 'Q8_0', 3 * 2 * ly.values).reshape(3, 2, heads, dim)
    check(np.array_equal(a.view(np.uint32), oracle[:, 0].view(np.uint32))
          and np.array_equal(b.view(np.uint32), oracle[:, 1].view(np.uint32))
          and np.array_equal(a, x) and np.array_equal(b, y),
          f'{heads} heads, width {dim}: decode bitwise own_dequant and exact known values')

# Literal blocks exercise decoder's wider domain: -128 codes, negative/zero
# scales and the smallest positive half subnormal are valid stored byte values.
ly = Q8KVLayout(2, 256)
raw_blocks = []
for word in (0, 0x3800, 0x3c01, 0xc000, 1, 0x8000, 0x7bff, 0x3555) * 8:
    raw_blocks.append(block([word & 255, word >> 8], [-128, -127, -1, 0, 1, 127]))
raw = np.frombuffer(b''.join(raw_blocks), np.uint8).reshape(2, ly.row_bytes)
a, b = decode_q8_kv(raw, ly)
oracle = own_dequant.dequant(raw.reshape(-1), 'Q8_0', 2 * 2 * ly.values).reshape(2, 2, 2, 256)
check(np.array_equal(a.view(np.uint32), oracle[:, 0].view(np.uint32))
      and np.array_equal(b.view(np.uint32), oracle[:, 1].view(np.uint32)),
      'literal finite Q8_0 blocks decode bitwise own_dequant including signed zeros and subnormals')
check(a[0, 0, 32:38].tolist() == [-64, -63.5, -.5, 0, .5, 63.5], 'independent half-scale decoded values')

rng = np.random.default_rng(81)
ly = Q8KVLayout(3, 256)
k = rng.normal(size=(3, 3, 512)).astype(np.float32)[:, :, ::2]
v = rng.normal(size=k.shape).astype(np.float32)
raw = encode_q8_kv(k, v, ly)
a, b = decode_q8_kv(raw, ly)
oracle = own_dequant.dequant(raw.reshape(-1), 'Q8_0', 3 * 2 * ly.values).reshape(3, 2, 3, 256)
check(np.array_equal(a.view(np.uint32), oracle[:, 0].view(np.uint32))
      and np.array_equal(b.view(np.uint32), oracle[:, 1].view(np.uint32)),
      'strided float32 inputs and multiple rows cross-check own decoder')
empty = np.empty((0, 3, 256), np.float32)
raw = encode_q8_kv(empty, empty, ly)
check(raw.shape == (0, ly.row_bytes) and raw.nbytes == 0 and ly.cache_bytes(0) == 0
      and decode_q8_kv(raw, ly)[0].shape == empty.shape, 'empty state view consumes zero bytes')

for heads, dim in ((0, 128), (-1, 128), (True, 128), (1.0, 128), (1, 0), (1, 127), (1, False), (1, 128.0)):
    refuses(lambda: Q8KVLayout(heads, dim), f'refuse invalid layout {heads!r}, {dim!r}')
for rows in (-1, True, 1.5):
    refuses(lambda: layout.cache_bytes(rows), f'refuse invalid row count {rows!r}')
k = np.zeros((1, 1, 128), np.float32)
for bad in (k.astype(np.float64), k.astype(np.int8), k[0], k[:, :, :-1], np.zeros((2, 1, 128), np.float32)):
    refuses(lambda: encode_q8_kv(k, bad, layout), 'refuse incorrect dtype, dimensions or mismatched K/V rows')
for value in (np.nan, np.inf, -np.inf, np.finfo(np.float32).max,
              np.nextafter(np.float32(0), np.float32(1)), np.float32(1e-37)):
    bad = k.copy()
    bad[0, 0, 0] = value
    refuses(lambda: encode_q8_kv(bad, k, layout), 'refuse nonfinite or unrepresentable nonzero block scale')
for bad in (np.zeros((1, 272), np.int8), np.zeros(272, np.uint8), np.zeros((1, 271), np.uint8)):
    refuses(lambda: decode_q8_kv(bad, layout), 'refuse incorrect raw dtype, dimensions or row byte count')
for word in (0x7c00, 0xfc00, 0x7e00):
    bad = np.zeros((1, 272), np.uint8)
    bad[0, :2] = [word & 255, word >> 8]
    refuses(lambda: decode_q8_kv(bad, layout), 'refuse nonfinite stored half scale')

print('RESULT', 'PASS' if ok else 'FAIL')
sys.exit(0 if ok else 1)
