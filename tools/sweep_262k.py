def missing(*p):
    """the inputs of p that are absent or short ([(path, why)]): a logits file (.bin / .npy) must hold at least NPOS rows of NV
    floats (a run still writing, or cut short, is short)"""
    out = []
    for x in p:
        if not os.path.exists(x): out.append((x, 'missing'))
        elif x.endswith(('.bin', '.npy')) and os.path.getsize(x) < NPOS * NV * 4: out.append((x, f'short ({os.path.getsize(x)} bytes < {NPOS * NV * 4})'))
    return out


def need(gate, *p, binding=True):
    """True when every input of `gate` is there; else the gate is NOT RUN: printed, recorded (NOT_RUN, or REPORTED_NOT_RUN for
    a reported-only number), and a binding gate NOT RUN keeps RESULT from PASS (fix after the sweep review, 11-05: cmp used to
    skip a gate with missing inputs silently)"""
    miss = missing(*p)
    if not miss: return True
    why = '; '.join(f'{os.path.relpath(x, S) if x.startswith(S) else x}: {w}' for x, w in miss)
    (NOT_RUN if binding else REPORTED_NOT_RUN).append((gate, why))
    print(f'NOT RUN {gate}{"" if binding else " (reported, not a gate)"}: {why}', flush=True)
    return False


