def cmp_result():
    """the cmp RESULT line and exit code: PASS only when every gate ran and passed; a gate NOT RUN (missing / short inputs) is
    RESULT NOT RUN (exit 3) unless one failed (RESULT FAIL, exit 1)"""
    if FAILS: return f'RESULT FAIL ({len(FAILS)})' + (f'; NOT RUN ({len(NOT_RUN)})' if NOT_RUN else ''), 1
    if NOT_RUN: return f'RESULT NOT RUN ({len(NOT_RUN)} gate(s) with missing / short inputs)', 3
    return 'RESULT PASS', 0


