def cstage_g3(R, TPC, small):
    """G3 (a) and (b) at a ~200K checkpoint (stage_g3's protocol at depth)"""
    pc, m, dr = R.pc, R.m, R.dr
    toks = seq_tokens(); other = TPC.toks_of('shell')
    N1 = 6000 if small else 200000; ROOT_, USER_ = 900, N1 - 2000
    r1 = toks[:N1]; mk1 = dict(root=ROOT_, user=USER_)
    # (a) restore from VRAM == from disk == the saved state; the entry's checkpoint bytes == the slot's
    pc.purge(); pc.reset(); t0 = time.perf_counter(); o1 = pc.prepare(r1, mk1); tcold = time.perf_counter() - t0
    d_pe = TPC.edigest(R, o1['st']['i0'])
    pe = [ck for ck in pc.ckpts if ck.pos == o1['st']['i0']][0]; slot_sha = [TPC.tsha(pc.buf[c][pe.slot]) for c in (0, 1)]
    pc.prepare(r1[:N1 - 1] + other[:300])                                      # a probe past the prompt end
    t0 = time.perf_counter(); rv = pc.restore(r1); R.sync(); tv = time.perf_counter() - t0; d_v = TPC.edigest(R, rv['st']['i0'])
    t0 = time.perf_counter(); nm = pc.park(); tpk = time.perf_counter() - t0; h = pc.store.index[nm]
    j = [i for i, x in enumerate(h['ckpts']) if x['pos'] == pe.pos and x['commit'] == pe.commit][0]
    blob = [np.zeros(pc.layout.nbytes[c], dtype=np.uint8) for c in (0, 1)]
    pc.store.read(nm, h, {h['ckpts'][j]['segs'][c]: [blob[c]] for c in (0, 1)})
    pc.reset(); t0 = time.perf_counter(); rd_ = pc.restore(r1); R.sync(); td = time.perf_counter() - t0; d_d = TPC.edigest(R, rd_['st']['i0'])
    NUMBERS['g3a'] = dict(pos=pe.pos, cold_s=tcold, restore_vram_s=tv, park_s=tpk, restore_disk_s=td, entry_mib=h['file_bytes'] / 2 ** 20, stops=o1['stops'])
    check(rv['source'] == 'vram' and rd_['source'] == 'disk' and not TPC.ddiff(d_v, d_pe) and not TPC.ddiff(d_d, d_pe) and
          [TPC._sha(b.tobytes()) for b in blob] == slot_sha,
          f'G3a at depth: the prompt-end checkpoint at {pe.pos} restored from VRAM (after a probe; {tv * 1e3:.0f} ms) == restored from disk (after a reset; '
          f'{td * 1e3:.0f} ms from a {h["file_bytes"] / 2 ** 30:.2f} GiB entry, parked in {tpk:.1f} s) == the state when taken, bitwise ({len(d_pe)} items); '
          f'the entry\'s checkpoint bytes == the VRAM slot\'s' + (f'; differ {TPC.ddiff(d_v, d_pe)[:3]} / {TPC.ddiff(d_d, d_pe)[:3]}' if TPC.ddiff(d_v, d_pe) or TPC.ddiff(d_d, d_pe) else ''))
    # (b) resume after a restore == resume without it, a decode-built span inside
    pc.purge(); pc.reset(); o1 = pc.prepare(r1, mk1)
    t1, s1 = TPC.lgen(R, o1['st'], r1, 48); pc.commit(t1, s1)
    app = toks[N1 + 100:N1 + 100 + (300 if small else 700)]
