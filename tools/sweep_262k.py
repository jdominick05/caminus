def check(ok, what):
    print(('PASS ' if ok else 'FAIL ') + what, flush=True)
    if not ok: FAILS.append(what)
    return ok


def comp():
    return open('/proc/sys/vm/compaction_proactiveness').read().strip()


def avail_mib():
    for l in open('/proc/meminfo'):
        if l.startswith('MemAvailable:'): return int(l.split()[1]) / 1024
    return -1


def host_note():
    return f'compaction_proactiveness {comp()}, MemAvailable {avail_mib():.0f} MiB'


def vram_used():
    return [int(open(f'/sys/class/drm/{c}/device/mem_info_vram_used').read()) / 2 ** 20 for c in ('card1', 'card2')]


