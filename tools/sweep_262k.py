# ---- the k3 rig ---------------------------------------------------------------------------------------------------------
class Rig:
    """FlashNextTP T = 4 (or T = 1 without a drafter) at max_ctx 262144, DFlash (device accept) on T = 4, the prefill at
    chunk 2048; the police attached before any pass"""
    def __init__(self, torch, coder, max_ctx=262144, T=4, drafter=True):
        from caminus import flashnext   # noqa: F401  (gguf-py on the path)
        from gguf import GGUFReader
        from caminus import dflash_k3 as dk, prefill as P, passpolice
        from caminus.flashnext_tp import FlashNextTP
        self.torch = torch; self.idle = vram_used()
        t0 = time.time()
        if drafter:
            rd = GGUFReader(dk.DRAFTER, 'r'); f = {x.name: x for x in rd.fields.values()}
            layers = [int(v) for v in f['dflash.target_layers'].contents()]; del rd, f
            self.dg = dk.geom(dk.DRAFTER)
            self.m = FlashNextTP(coder, ntok=T, max_ctx=max_ctx, feature_layers=layers, feature_card=0,
                                 vram_drafters=(('dflash', self.dg, None),), vram_prefill=2048)
        else:
            self.dg = None
            self.m = FlashNextTP(coder, ntok=T, max_ctx=max_ctx, vram_prefill=2048)
        self.pol = passpolice.of(self.m); atexit.register(lambda: print(self.pol.summary(), flush=True))
        self.df = dk.DFlashK3(self.m, dk.DRAFTER) if drafter else None
        self.dr = dk.DFlashK3Drafter(self.df) if drafter else None
        self.pf = P.Prefill(self.m, chunk=2048)
        self.sync()
        vp = self.m.vram_plan
        print(f'rig: T = {T}, max_ctx {max_ctx}, qsa {self.m.qsa} dual {self.m.dual}, drafter {"DFlash (device accept)" if drafter else "none"}, '
              f'loaded in {time.time() - t0:.1f} s; device VRAM {[round(x) for x in vram_used()]} MiB (idle {[round(x) for x in self.idle]}); '
              f'plan fixed {[round(x) for x in vp["fixed_mib"]]} ctx {vp["ctx_mib"]:.0f} prefill {[round(x) for x in vp["prefill_mib"]]} drafters '
              f'{[round(x) for x in vp["drafters_mib"]]} MiB; T* {self.pf.crossover}; {host_note()}', flush=True)

    def sync(self):
        for d in (0, 1): self.torch.cuda.synchronize(d)

    def projection(self):
        vp = self.m.vram_plan
        return [vp['fixed_mib'][c] + vp['ctx_mib'] + vp['reserve_mib'][c] + vp['drafters_mib'][c] + vp['prefill_mib'][c] for c in (0, 1)]


