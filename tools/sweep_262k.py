def stage_curves(R, small):
    from caminus import spec, longctx
    m, pf, dr = R.m, R.pf, R.dr
    toks = seq_tokens(); n_new = 32 if small else 128
    depths = (2048, 8192) if small else CURVE_DEPTHS
    print(f'  curves: {host_note()}; depths {depths}; {n_new} DFlash tokens per smoke text', flush=True)
    res = dict(compaction=comp(), mem_available_mib=avail_mib(), depths={})
    def ttft_plain(pr):
        R.sync(); t0 = time.perf_counter(); spec.generate(m, pr, 1, longctx.Repeat(), prefill=pf); R.sync()
        return (time.perf_counter() - t0) * 1e3
    ttft_plain(toks[:4096] + smoke_prompt('prose'))             # (warm-up)
    for D in depths:
        reps = 3 if D <= 32768 else 1
        row = dict(ttft_plain_ms=[], dflash={})
        for r in range(reps): row['ttft_plain_ms'].append(ttft_plain(toks[:D] + smoke_prompt('prose')))
        for t in TEXTS:
            pr = toks[:D] + smoke_prompt(t); st = {}
            R.sync(); t0 = time.perf_counter(); g = dr.generate(m, pr, n_new, st, prefill=pf); R.sync(); wall = time.perf_counter() - t0
            ng = st['gen_tokens'] - 1; gs = st['gen_seconds']; gp = st['gen_passes']
            row['dflash'][t] = dict(ttft_ms=(st['seconds'] - gs) * 1e3, ms_per_token=gs / ng * 1e3, tok_s=ng / gs, tokens_per_pass=ng / gp,
                                    accepted_per_pass=st['accepted'] / gp, wall_s=wall, tokens=[int(x) for x in g[len(pr):]], n_prompt=len(pr))
        n = D + NP_SMOKE; tp = float(np.median(row['ttft_plain_ms'])); tdf = float(np.median([v['ttft_ms'] for v in row['dflash'].values()]))
        row.update(n_prompt=n, ttft_plain_median_ms=tp, prefill_tok_s=n / tp * 1e3, ttft_dflash_median_ms=tdf, prefill_dflash_tok_s=n / tdf * 1e3)
        res['depths'][D] = row
        print(f'  TIME depth {D:6d} (+ a {NP_SMOKE}-token smoke text): TTFT from empty {tp:9.1f} ms = {n / tp * 1e3:5.0f} tok/s (no DFlash inject, '
              f'runs {", ".join(f"{x:.0f}" for x in row["ttft_plain_ms"])}); with the inject {tdf:9.1f} ms ({n / tdf * 1e3:5.0f} tok/s); DFlash decode ms/token '
              + ' / '.join(f'{row["dflash"][t]["ms_per_token"]:.2f}' for t in TEXTS) + ' (prose / code / shell; tok/s '
              + ' / '.join(f'{row["dflash"][t]["tok_s"]:.1f}' for t in TEXTS) + ', tokens per pass '
              + ' / '.join(f'{row["dflash"][t]["tokens_per_pass"]:.2f}' for t in TEXTS) + f'); {host_note()}', flush=True)
    # 8K appends at depth (speed7's protocol, with the DFlash inject)
    L8 = 8192; res['append'] = {}
    for D0 in ((4096,) if small else (131072, 250000)):
        m.reset(); dr.reset(); st = pf.run(toks, 0, 0, D0, dr); R.sync(); t0 = time.perf_counter()
        n = D0 + L8; pf.run(toks, st['i0'], st['commit'], n - 1, dr)
        spec.loop(m, list(toks[:n]), n - 1, 0, n + 1, dr)
        R.sync(); ms = (time.perf_counter() - t0) * 1e3
        res['append'][D0] = dict(ms=ms, tok_s=L8 / ms * 1e3)
        print(f'  TIME 8192-token append at depth {D0} (positions {D0} .. {n - 1}), with the DFlash inject: {ms:.1f} ms = {L8 / ms * 1e3:.0f} tok/s '
              f'(one run); {host_note()}', flush=True)
    os.makedirs(K3OUT, exist_ok=True)
    json.dump(res, open(os.path.join(K3OUT, f'curves{"_small" if small else ""}.json'), 'w'), indent=1, default=str)
    NUMBERS['curves'] = {k: v for k, v in res.items() if k != 'depths'} | dict(depths={D: {k: v for k, v in r.items() if k != 'dflash'} |
                                                                                        dict(dflash={t: {k: v for k, v in x.items() if k != 'tokens'} for t, x in r['dflash'].items()})
                                                                                        for D, r in res['depths'].items()})


# ---- stage: launch (the longest launch at depth) --------------------------------------------------------------------------
class LaunchTimer:
    """caminus.hip.RECORD while one prefill chunk runs: both cards synced before and after each launch (no kernel of the
    prefill spins on the peer: its exchange orders by HIP events only, so serializing adds no wait), the launch's wall time
    recorded by kernel name; never a K3 launch (the persistent kernels wait on each other's exchange flags)"""
    def __init__(self, torch):
        self.torch = torch; self.t = {}; self.t0 = None; self.n = 0

    def _sync(self):
        for d in (0, 1): self.torch.cuda.synchronize(d)

    def intercept(self, k, grid, block, vals, shmem, s):
        assert k.name not in ('k3_run', 'k3_run2'), f'LaunchTimer: a K3 launch ({k.name}) inside the timed chunk'
        self._sync(); self.t0 = time.perf_counter(); return False

    def launched(self, k, grid, block, vals, shmem, s):
        self._sync(); dt = (time.perf_counter() - self.t0) * 1e3; self.n += 1
        self.t.setdefault(k.name, []).append(dt)


def stage_launch(R, small):
    from caminus import hip, longctx
    m, pf, pol = R.m, R.pf, R.pol
    toks = seq_tokens(); D0 = 4096 if small else 259584; D1 = D0 + 2048
    m.reset(); t0 = time.perf_counter(); st = pf.run(toks, 0, 0, D0); R.sync()
    print(f'  launch: fill to {D0} in {time.perf_counter() - t0:.1f} s', flush=True)
    lt = LaunchTimer(R.torch); assert hip.RECORD is None
    hip.RECORD = lt
    try: pf.run(toks, st['i0'], st['commit'], D1); R.sync()
    finally: hip.RECORD = None
