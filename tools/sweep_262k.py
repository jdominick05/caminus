    TA, sT = TPC.lgen(R, sA, r2, 32); pc.extend(TA, sT)
    pc.prepare(r2[:o2['st']['i0']] + other[:200])                               # probe
    res = {}
    for how in ('vram', 'disk'):
        if how == 'disk': pc.park(); pc.reset()
        ob = pc.prepare(r2, mk2); DB = TPC.edigest(R, ob['st']['i0'])
        LB, sB = TPC.first(R, ob['st'], r2); pc.extend(r2, sB)
        TB, sTB = TPC.lgen(R, sB, r2, 32); pc.extend(TB, sTB)
        res[how] = dict(source=ob['source'], cached=ob['cached'], ms=ob['ms'])
        check(ob['cached'] == o2['st']['i0'] and not TPC.ddiff(DA, DB) and np.array_equal(LA, LB) and TB == TA,
              f'G3b at depth ({how}): r2 = a cold {N1} + 48 decoded (DFlash) + {len(app)} appended, after a probe restored from {ob["source"]} ({ob["cached"]} '
              f'reused, {ob["ms"]}) == resumed without a restore: state ({len(DA)} items), first logits bitwise, 32 tokens'
              + (f'; differ {TPC.ddiff(DA, DB)[:4]}' if TPC.ddiff(DA, DB) else ''))
    NUMBERS['g3b'] = res
    pc.reset()


