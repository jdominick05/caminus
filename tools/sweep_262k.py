def stage_soak(R, small):
    from caminus import longctx
    m, dr, pol = R.m, R.dr, R.pol
    toks = seq_tokens()
    wins = (4096, 8192) if small else WINDOWS
    end = max(wins) + NPOS; T = m.ntok
    assert all(N % T == 0 for N in wins) and end + 128 + 2 * T <= m.max_ctx and len(toks) >= end + 8
    print(f'  soak: positions 0 .. {end - 1} of seq.ids in T = {T} passes, DFlash inject every pass, windows {wins}; {host_note()}', flush=True)
    m.reset(); dr.reset()
    keep = {}; i0 = commit = 0; t0 = tl = time.perf_counter(); il = 0; worst = worst_net = 0.0; nb0 = len(m.bails)
    marks = {}
    while i0 < end:
        pp = pol.begin('sweep.soak', i0); lo = m.verify(toks, i0, commit); pp = pol.end(pp, 150.0)
        worst = max(worst, pp['raw']); worst_net = max(worst_net, pp['net'])
        for N in wins:
            if N <= i0 < N + NPOS:
                if N not in keep: keep[N] = np.zeros((NPOS, NV), np.float32)
                keep[N][i0 - N:i0 - N + T] = lo.float().cpu().numpy()
        dr.inject(i0, m.features); dr.flush()
        commit = T; i0 += T
        for b in (2048, 2052, 4096, 8192, 16384, 32768, 65536, 131072, 196608, 262144):   # pass times around the boundaries
            if i0 - T < b <= i0 + 2 * T: marks.setdefault(b, []).append(round(pp['raw'], 2))
        t = time.perf_counter()
        if t - tl >= 60 or i0 >= end:
            print(f'  soak: {i0}/{end}, {(i0 - il) / (t - tl):.0f} tok/s now, {t - t0:.0f} s, longest pass {worst:.1f} ms raw / {worst_net:.1f} net, '
                  f'last pass {pp["raw"]:.1f} ms, bails {len(m.bails) - nb0}; {host_note()}', flush=True)
            tl, il = t, i0
    R.sync(); dt = time.perf_counter() - t0
    r0, r1 = m.check_replicas()
    un = pol.unexplained_bails()
    res = dict(end=end, seconds=dt, passes=end // T, longest_raw_ms=worst, longest_net_ms=worst_net, bails=len(m.bails) - nb0,
               unexplained_bails=un, replicas=[r0, r1], boundary_pass_ms=marks, compaction=comp(), police=pol.mode())
    check(not un and r0 and r1 and m.poisoned is None,
          f'soak: {end} positions in {end // T} policed passes ({dt:.0f} s, {end / dt:.0f} tok/s), DFlash inject every pass; longest pass {worst:.1f} ms raw, '
          f'{worst_net:.1f} ms net of evictions (limit 150); bails {len(m.bails) - nb0}, unexplained {len(un)}; replicas {r0}/{r1}; compaction_proactiveness {comp()}')
    print(pol.summary(), flush=True)
    # DFlash at the cap: from the soak's state, 96 tokens with DFlash vs 96 plain (a snapshot: this rig holds no cache tier)
    st = dict(i0=end, commit=T)
    snap = longctx.snapshot(m, st, dr)
    sa = {}; a, sta = longctx.generate(m, st, toks[:end], 96, draft=dr, stats=sa)
    longctx.restore(m, snap, dr)
    b, stb = longctx.generate(m, st, toks[:end], 96, draft=None)
    longctx.release(snap)
    acc = sa.get('accepted', 0) / max(1, sa.get('gen_passes', 1))
    res['dflash_at_cap'] = dict(same=a == b, accepted_per_pass=acc, gen_tokens=sa.get('gen_tokens'), gen_seconds=sa.get('gen_seconds'),
                                last_pos=sta['i0'])
    check(a == b and m.poisoned is None, f'soak: from position {end}, 96 tokens with DFlash (device accept, up to position {sta["i0"]}) == 96 plain, '
          f'bitwise tokens; accepted {acc:.2f} drafts per pass')
    os.makedirs(K3OUT, exist_ok=True)
    for N, arr in keep.items():
        p = os.path.join(K3OUT, f'k3_1tok_N{N}{"_small" if small else ""}.npy'); save_rows(p, arr, toks, N); res.setdefault('saved', []).append(p)
    NUMBERS['soak'] = res


# ---- stage: g4 (K3 prefill-then-decode at each window) --------------------------------------------------------------------
def stage_g4(R, small):
    from caminus import longctx
    m, pf = R.m, R.pf
    toks = seq_tokens(); out = {}
    for N in ((4096, 8192) if small else WINDOWS):
        m.reset(); R.sync(); t0 = time.perf_counter()
        st = pf.run(toks, 0, 0, N); R.sync(); t1 = time.perf_counter()
        lg, _ = longctx.teacher_forced(m, dict(i0=st['i0'], commit=0), toks, NPOS); t2 = time.perf_counter()
        r0, r1 = m.check_replicas()
        p = os.path.join(K3OUT, f'k3_pd_N{N}{"_small" if small else ""}.npy'); os.makedirs(K3OUT, exist_ok=True)
        save_rows(p, lg.numpy(), toks, N)
        out[N] = dict(prefill_s=t1 - t0, decode_s=t2 - t1, replicas=[r0, r1], path=p)
        check(r0 and r1 and m.poisoned is None, f'g4 N={N}: the batched prefill of [0, {N}) in {t1 - t0:.1f} s ({N / (t1 - t0):.0f} tok/s), then {NPOS} positions '
              f'teacher-forced through K3 ({t2 - t1:.1f} s); replicas {r0}/{r1}; saved {os.path.basename(p)}')
    NUMBERS['g4'] = out


