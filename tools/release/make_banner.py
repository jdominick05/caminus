"""docs/banner.svg: the CAMINUS block-letter wordmark (5-row pixel font, three frost bands, two outline echoes), taking
turns with QWAMINUS, in the control panel's palette (panel/top_main.go: the Nord-style colours, `◆ caminus` in the frost
accent on the panel's background).

  python -I tools/release/make_banner.py [docs/banner.svg]
  python -I tools/release/make_banner.py --social [docs/social-preview.svg]

--social draws the repository's social preview (the card link previews show) at GitHub's 1280 x 640: the wordmark,
the README's two lines and four badges, all inside GitHub's 80 px safe border. GitHub takes a PNG: render it at its size
with any SVG renderer, e.g. (the command that drew docs/social-preview.png)

  google-chrome --headless=new --hide-scrollbars --window-size=1280,640 \\
      --screenshot="$PWD/docs/social-preview.png" "file://$PWD/docs/social-preview.svg"

and upload the PNG in the repository's Settings > General > Social preview."""
import sys

GLYPHS = {
    'C': ['#####', '#....', '#....', '#....', '#####'],
    'A': ['#####', '#...#', '#####', '#...#', '#...#'],
    'M': ['#...#', '##.##', '#.#.#', '#...#', '#...#'],
    'I': ['###', '.#.', '.#.', '.#.', '###'],
    'N': ['#...#', '##..#', '#.#.#', '#..##', '#...#'],
    'U': ['#...#', '#...#', '#...#', '#...#', '#####'],
    'S': ['#####', '#....', '#####', '....#', '#####'],
    'Q': ['#####.', '#...#.', '#...#.', '#..##.', '######'],      # the square O with a tail out of its corner
    'W': ['#...#', '#...#', '#.#.#', '##.##', '#...#'],           # M upside down
}
CELL, GAP = 26, 1                    # px per pixel cell, letter gap in cells
BANDS = ['#8fbcbb', '#8fbcbb', '#88c0d0', '#88c0d0', '#81a1c1']   # row colors: the panel's teal, accent, blue (cTeal / cAccent / cBlue)
ECHO = [(9, 9, 0.75), (16, 16, 0.4)]                              # outline offsets (px) and opacity, the panel's muted grey
BG = ('#1d2129', '#242a35')                                       # the panel's background, then a step toward its dim grey
EDGE, ECHO_C = '#3b4252', '#6b7489'                               # border (cDim), echoes (cMuted)
W, H = 1280, 240


def cells(word):
    x0, out = 0, []
    for ch in word:
        g = GLYPHS[ch]
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == '#': out.append((x0 + c, r))
        x0 += len(g[0]) + GAP
    return out, x0 - GAP


def outline(cs):
    """boundary edges of the union of cells, as one path of unit segments (in cell units)"""
    s, segs = set(cs), []
    for (x, y) in cs:
        if (x, y - 1) not in s: segs.append(((x, y), (x + 1, y)))
        if (x, y + 1) not in s: segs.append(((x, y + 1), (x + 1, y + 1)))
        if (x - 1, y) not in s: segs.append(((x, y), (x, y + 1)))
        if (x + 1, y) not in s: segs.append(((x + 1, y), (x + 1, y + 1)))
    return segs


# The README banner swaps two words: CAMINUS for 3.6 s, a 0.4 s cross-fade, QWAMINUS (Caminus runs Qwen models) for
# 3.6 s, and back. CSS keyframes, which browsers run in an <img> too; a reader whose system asks for less motion sees
# CAMINUS only. Both words are drawn at one cell size, the one QWAMINUS fits at (46 cells) inside an 80 px margin.
BANNER_WORDS = ('CAMINUS', 'QWAMINUS')
BANNER_CELL = 24
SWAP = """  <style>
    .w0 { animation: swap 8s infinite; }
    .w1 { animation: swap 8s infinite; animation-delay: -4s; }
    @keyframes swap { 0%, 45% { opacity: 1; } 50%, 95% { opacity: 0; } 100% { opacity: 1; } }
    @media (prefers-reduced-motion: reduce) { .w0 { animation: none; } .w1 { animation: none; opacity: 0; } }
  </style>"""


def main(path):
    echo = [(dx * BANNER_CELL // CELL, dy * BANNER_CELL // CELL, op) for dx, dy, op in ECHO]
    oy = (H - 5 * BANNER_CELL - echo[-1][1]) // 2
    p = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-labelledby="t">',
         '  <title id="t">Caminus</title>',
         '  <!-- Generated by tools/release/make_banner.py: a 5-row pixel font, filled in three frost bands, with two offset grey',
         '       outline echoes. The echoes trace each letter\'s real edge (the boundary of its filled cells). CAMINUS and',
         '       QWAMINUS take turns. -->',
         SWAP,
         f'  <defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{BG[0]}"/>'
         f'<stop offset="1" stop-color="{BG[1]}"/></linearGradient></defs>',
         f'  <rect x="0.5" y="0.5" width="{W - 1}" height="{H - 1}" rx="14" fill="url(#bg)" stroke="{EDGE}"/>']
    for i, word in enumerate(BANNER_WORDS):
        cs, ncol = cells(word)
        ox = (W - ncol * BANNER_CELL - echo[-1][0]) // 2
        assert ox >= 80, f'{word} leaves the margin'
        p.append(f'  <g class="w{i}">')
        p += wordmark(cs, ox, oy, BANNER_CELL, echo, indent='    ')
        p.append('  </g>')
    p.append('</svg>')
    open(path, 'w').write('\n'.join(p) + '\n')


def wordmark(cs, ox, oy, cell, echo, indent='  '):
    """the letters at (ox, oy): the echo outlines first, then the bands"""
    p, segs = [], outline(cs)
    for dx, dy, op in reversed(echo):
        d = ' '.join(f'M{ox + dx + a[0] * cell} {oy + dy + a[1] * cell}L{ox + dx + b[0] * cell} {oy + dy + b[1] * cell}' for a, b in segs)
        p.append(f'{indent}<path d="{d}" fill="none" stroke="{ECHO_C}" stroke-opacity="{op}" stroke-width="2" stroke-linecap="square"/>')
    for r, color in enumerate(BANDS):
        d = ' '.join(f'M{ox + x * cell} {oy + y * cell}h{cell}v{cell}h-{cell}z' for x, y in cs if y == r)
        p.append(f'{indent}<path d="{d}" fill="{color}" shape-rendering="crispEdges"/>')
    return p


SOCIAL_W, SOCIAL_H, SAFE = 1280, 640, 80     # GitHub's social preview size and its recommended border (40 pt at 2x)
SOCIAL_LINES = ('Fast local coding models on your AMD Radeon RX 7900 cards',          # the README's first two lines
                'An inference engine written from the GPU kernels up for RDNA3')
SOCIAL_BADGES = [('RX 7900 XTX / XT', '#8fbcbb'), ('Qwen models', '#88c0d0'),          # the README's badge colours
                 ('OpenAI / Anthropic API', '#81a1c1'), ('AGPL-3.0', '#b48ead')]
SANS = "'Ubuntu Sans',Cantarell,Inter,'Segoe UI',system-ui,sans-serif"
MONO = "'Ubuntu Sans Mono','DejaVu Sans Mono',Menlo,Consolas,monospace"


def social(path):
    cell = 22
    cs, ncol = cells('CAMINUS')
    echo = [(dx * cell // CELL, dy * cell // CELL, op) for dx, dy, op in ECHO]
    ox, oy = (SOCIAL_W - ncol * cell - echo[-1][0]) // 2, 150
    p = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{SOCIAL_W}" height="{SOCIAL_H}" viewBox="0 0 {SOCIAL_W} {SOCIAL_H}" role="img" aria-labelledby="t">',
         '  <title id="t">Caminus</title>',
         '  <!-- Generated by tools/release/make_banner.py (its social mode): the repository\'s social preview (GitHub\'s 1280 x 640, content',
         f'       inside its {SAFE} px border). -->',
         f'  <defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{BG[0]}"/>'
         f'<stop offset="1" stop-color="{BG[1]}"/></linearGradient></defs>',
         f'  <rect width="{SOCIAL_W}" height="{SOCIAL_H}" fill="url(#bg)"/>']
    p += wordmark(cs, ox, oy, cell, echo)
    y = oy + 5 * cell + echo[-1][1] + 78
    p.append(f'  <text x="{SOCIAL_W // 2}" y="{y}" text-anchor="middle" font-family="{SANS}" font-size="34" font-weight="bold" fill="#e5e9f0">{SOCIAL_LINES[0]}</text>')
    p.append(f'  <text x="{SOCIAL_W // 2}" y="{y + 46}" text-anchor="middle" font-family="{SANS}" font-size="25" fill="#9aa5b8">{SOCIAL_LINES[1]}</text>')
    # badges: monospace, so their widths are known (0.6 em a character)
    fs, padx, gap, bh = 19, 14, 14, 34
    widths = [len(t) * fs * 0.6 + 2 * padx for t, _ in SOCIAL_BADGES]
    x = (SOCIAL_W - sum(widths) - gap * (len(widths) - 1)) / 2
    by = y + 94
    for (t, color), w in zip(SOCIAL_BADGES, widths):
        p.append(f'  <rect x="{x:.1f}" y="{by}" width="{w:.1f}" height="{bh}" rx="6" fill="{color}"/>'
                 f'<text x="{x + w / 2:.1f}" y="{by + 23}" text-anchor="middle" font-family="{MONO}" font-size="{fs}" font-weight="bold" fill="#1b1f27">{t}</text>')
        x += w + gap
    assert by + bh <= SOCIAL_H - SAFE and oy >= SAFE, 'the card left the safe border'
    p.append('</svg>')
    open(path, 'w').write('\n'.join(p) + '\n')


if __name__ == '__main__':
    if sys.argv[1:2] == ['--social']:
        social(sys.argv[2] if len(sys.argv) > 2 else 'docs/social-preview.svg')
    else:
        main(sys.argv[1] if len(sys.argv) > 1 else 'docs/banner.svg')
