"""Vendor llama.cpp's gguf-py reader (MIT) into python/caminus/_vendor/gguf/ (docs/dev/packaging.md, impl:package).

  python -I tools/release/vendor_gguf.py [--commit 5aeac37a35] [--src ~/src/ignite-llama]   # (re)write python/caminus/_vendor/gguf/
  python -I tools/release/vendor_gguf.py --check                                            # exit 1 if the files differ

Why vendored: the Coder holds Q2_0 tensors (GGML type 42), added to gguf-py on 2026-07-07 (llama.cpp bec4772f6) after its
last version bump (0.19.0, a290ce626), so a gguf from PyPI at or below 0.19.0 refuses the file (GGUFReader maps every tensor
type through GGMLQuantizationType). The engine read the fork's gguf-py tree before; the fork's gguf-py (its development commit
842653396, published as e4e3f8eda on github.com/jdominick05/ignite-llama with gguf-py/ unchanged) equals upstream's at
5aeac37a35 (no diff), the commit taken here.

The four modules the reader needs (constants.py, gguf_reader.py, quants.py, lazy.py) are taken from git history at --commit
(`git show`, not a working tree, so the copy is reproducible), verbatim below a header with gguf-py's MIT notice. The package
init is our own (INIT below): upstream's also imports the writer, tensor mapping, vocab, utility and metadata modules, which
need PyYAML / requests / sentencepiece; the engine only reads GGUF files. caminus.config.ensure_gguf puts the directory on
sys.path as `gguf`, the way the fork's tree was.
"""
