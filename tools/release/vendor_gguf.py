ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'python', 'caminus', '_vendor', 'gguf')
COMMIT = '5aeac37a35'
FILES = ('constants.py', 'gguf_reader.py', 'quants.py', 'lazy.py')

