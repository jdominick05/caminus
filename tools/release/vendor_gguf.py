INIT_BODY = """from .constants import *
from .lazy import *
from .gguf_reader import *
from .quants import *
"""


def header(name, commit, changed):
    lines = [f'Vendored from llama.cpp\'s gguf-py (MIT): gguf-py/gguf/{name} at upstream commit {commit}',
             '(https://github.com/ggml-org/llama.cpp; the ignite-llama fork\'s gguf-py at e4e3f8eda, '
             'github.com/jdominick05/ignite-llama, is identical).',
             'Generated by tools/release/vendor_gguf.py (do not edit by hand; rerun it). Listed in THIRD_PARTY.md.',
             changed, '', *MIT.splitlines()]
    return ''.join(('# ' + x).rstrip() + '\n' for x in lines) + '\n'


def render(src, commit):
    out = {}
    for f in FILES:
        body = subprocess.run(['git', '-C', src, 'show', f'{commit}:gguf-py/gguf/{f}'], check=True, capture_output=True, text=True).stdout
        out[f] = header(f, commit, 'Unchanged from the original below this header.') + body
    out['__init__.py'] = header('__init__.py', commit, 'Changed: reduced to the reader (constants, lazy, gguf_reader, quants); upstream also '
                                'imports gguf_writer, tensor_mapping, vocab, utility and metadata.') + INIT_BODY
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--commit', default=COMMIT)
    ap.add_argument('--src', default=os.environ.get('IGNITE', os.path.expanduser('~/src/ignite-llama')),
                    help='a llama.cpp git tree holding --commit (default $IGNITE or ~/src/ignite-llama)')
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    files = render(a.src, a.commit)
    bad = []
    for f, txt in files.items():
        p = os.path.join(OUT, f)
        if a.check:
            try: cur = open(p).read()
            except OSError: cur = None
            if cur != txt: bad.append(f)
        else:
            os.makedirs(OUT, exist_ok=True)
            with open(p, 'w') as fh: fh.write(txt)
            print(p)
    if a.check:
        extra = sorted(set(os.listdir(OUT)) - set(files) - {'__pycache__'}) if os.path.isdir(OUT) else []
        if bad or extra:
            print(f'vendor_gguf: differs from {a.commit}: {bad} extra {extra}'); return 1
        print(f'vendor_gguf: python/caminus/_vendor/gguf equals gguf-py at {a.commit} ({len(files)} files)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
