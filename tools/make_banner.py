"""docs/banner.svg: the CAMINUS block-letter wordmark (5-row pixel font, three molten bands, two steel outline echoes)."""
import sys

GLYPHS = {
    'C': ['#####', '#....', '#....', '#....', '#####'],
    'A': ['#####', '#...#', '#####', '#...#', '#...#'],
    'M': ['#...#', '##.##', '#.#.#', '#...#', '#...#'],
    'I': ['###', '.#.', '.#.', '.#.', '###'],
    'N': ['#...#', '##..#', '#.#.#', '#..##', '#...#'],
    'U': ['#...#', '#...#', '#...#', '#...#', '#####'],
    'S': ['#####', '#....', '#####', '....#', '#####'],
}
CELL, GAP = 26, 1                    # px per pixel cell, letter gap in cells
BANDS = ['#ffc98a', '#ffc98a', '#e8793a', '#e8793a', '#b4561f']   # row colors: pale molten, molten, deep ember
ECHO = [(9, 9, 0.55), (16, 16, 0.32)]                             # outline offsets (px) and opacity, steel
W, H = 1280, 240


def cells(word):
    x0, out = 0, []
    for ch in word:
        g = GLYPHS[ch]
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == '#': out.append((x0 + c, r))
        x0 += len(g[0]) + GAP
    return out, x0 - GAP


def outline(cs):
    """boundary edges of the union of cells, as one path of unit segments (in cell units)"""
    s, segs = set(cs), []
    for (x, y) in cs:
        if (x, y - 1) not in s: segs.append(((x, y), (x + 1, y)))
        if (x, y + 1) not in s: segs.append(((x, y + 1), (x + 1, y + 1)))
        if (x - 1, y) not in s: segs.append(((x, y), (x, y + 1)))
        if (x + 1, y) not in s: segs.append(((x + 1, y), (x + 1, y + 1)))
    return segs


def main(path):
    cs, ncol = cells('CAMINUS')
    ox = (W - ncol * CELL - ECHO[-1][0]) // 2
    oy = (H - 5 * CELL - ECHO[-1][1]) // 2
    p = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" aria-labelledby="t">',
         '  <title id="t">Caminus</title>',
         '  <!-- Generated by tools/make_banner.py: a 5-row pixel font, filled in three molten bands, with two offset steel',
         '       outline echoes. The echoes trace each letter\'s real edge (the boundary of its filled cells). -->',
         '  <defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#1b2127"/>'
         '<stop offset="1" stop-color="#252e36"/></linearGradient></defs>',
         f'  <rect x="0.5" y="0.5" width="{W - 1}" height="{H - 1}" rx="14" fill="url(#bg)" stroke="#3a444e"/>']
    segs = outline(cs)
    for dx, dy, op in reversed(ECHO):
        d = ' '.join(f'M{ox + dx + a[0] * CELL} {oy + dy + a[1] * CELL}L{ox + dx + b[0] * CELL} {oy + dy + b[1] * CELL}' for a, b in segs)
        p.append(f'  <path d="{d}" fill="none" stroke="#a9b6c4" stroke-opacity="{op}" stroke-width="2" stroke-linecap="square"/>')
    for r, color in enumerate(BANDS):
        row = [(x, y) for (x, y) in cs if y == r]
        d = ' '.join(f'M{ox + x * CELL} {oy + y * CELL}h{CELL}v{CELL}h-{CELL}z' for x, y in row)
        p.append(f'  <path d="{d}" fill="{color}" shape-rendering="crispEdges"/>')
    p.append('</svg>')
    open(path, 'w').write('\n'.join(p) + '\n')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'docs/banner.svg')
